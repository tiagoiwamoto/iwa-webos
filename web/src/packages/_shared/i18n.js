export const intlLocale = id =>
  ({en: 'en', pt_BR: 'pt-BR', pt_PT: 'pt-PT', es: 'es', ja: 'ja', zh: 'zh'})[id] || 'en';

export const getLocale = core => {
  try {
    return core.make('osjs/settings').get('webos', 'locale') || 'en';
  } catch (e) {
    return 'en';
  }
};

// OS.js core only ships these translations — dialogs fall back to en_EN
const OSJS_LOCALE = {en: 'en_EN', pt_BR: 'pt_BR', zh: 'zh_CN'};

export const setLocale = (core, id) => {
  const s = core.make('osjs/settings');
  s.set('webos', 'locale', id);
  s.set('osjs/locale', 'language', OSJS_LOCALE[id] || 'en_EN');
  return s.save()
    .then(() => document.dispatchEvent(new CustomEvent('webos:locale')));
};

export const useI18n = core => {
  const t = (key, vars) => {
    const dot = key.indexOf('.');
    const ns = dot > 0 ? key.slice(0, dot) : 'common';
    const k = dot > 0 ? key.slice(dot + 1) : key;
    const loc = getLocale(core);
    const dict = DICTS[ns] || {};
    let s = (dict[loc] && dict[loc][k]) || (dict.en && dict.en[k]) || key;
    if (vars) {
      s = s.replace(/\{(\w+)\}/g, (m, v) => vars[v] !== undefined ? vars[v] : m);
    }
    return s;
  };
  const onLocale = fn => {
    const h = () => fn();
    document.addEventListener('webos:locale', h);
    return () => document.removeEventListener('webos:locale', h);
  };
  return {t, onLocale, locale: () => getLocale(core)};
};

// package metadata titles use OS.js locale ids (en_EN, pt_BR, ...)
const META_LOCALE = {en: 'en_EN', pt_BR: 'pt_BR', pt_PT: 'pt_PT',
  es: 'es_ES', ja: 'ja_JP', zh: 'zh_CN'};

export const metaTitle = (core, m) => {
  const title = (m && m.title) || {};
  return title[META_LOCALE[getLocale(core)]] || title.en_EN ||
    (m && m.name) || '';
};

